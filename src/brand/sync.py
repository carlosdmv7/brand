"""Write a rendered block into a file between markers, or check that it is current.

Only the text between the markers is owned by this package. A file without
markers is refused rather than guessed at: the first adoption is a deliberate,
reviewed edit (delete the hand-written theme, paste the markers), never an
automatic one.
"""

from __future__ import annotations

from dataclasses import dataclass
import difflib
from pathlib import Path


@dataclass(frozen=True)
class Markers:
    start: str
    end: str


TOML = Markers(
    start="# >>> brand — generated by `brand sync streamlit`. Do not edit by hand.",
    end="# <<< brand",
)
CSS = Markers(
    start="/* >>> brand — generated by `brand sync css`. Do not edit by hand. */",
    end="/* <<< brand */",
)


class SyncError(Exception):
    """The target file cannot be synced as it stands."""


def _locate(lines: list[str], markers: Markers, path: Path) -> tuple[int, int]:
    starts = [i for i, line in enumerate(lines) if line.strip() == markers.start]
    ends = [i for i, line in enumerate(lines) if line.strip() == markers.end]
    if not starts and not ends:
        raise SyncError(
            f"{path}: no brand markers. Delete the hand-written block it replaces "
            f"and put these two lines where it went:\n\n{markers.start}\n{markers.end}"
        )
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise SyncError(f"{path}: expected exactly one start marker followed by one end marker")
    return starts[0], ends[0]


def apply(text: str, body: str, markers: Markers, path: Path) -> str:
    """Return ``text`` with the managed block replaced by ``body``."""
    lines = text.splitlines()
    start, end = _locate(lines, markers, path)
    new = [*lines[: start + 1], *body.splitlines(), *lines[end:]]
    return "\n".join(new) + "\n"


def sync(path: Path, body: str, markers: Markers, *, check: bool) -> str | None:
    """Bring ``path`` up to date; with ``check``, only report.

    Returns ``None`` when the file was already current, otherwise the unified
    diff between the file and the brand (written to disk unless ``check``).
    """
    if not path.exists():
        raise SyncError(f"{path}: file not found")
    current = path.read_text(encoding="utf-8")
    wanted = apply(current, body, markers, path)
    if wanted == current:
        return None
    if not check:
        path.write_text(wanted, encoding="utf-8")
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        wanted.splitlines(keepends=True),
        fromfile=f"{path} (on disk)",
        tofile=f"{path} (brand)",
    )
    return "".join(diff)
